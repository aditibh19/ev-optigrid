import {test,expect} from '@playwright/test';
test('dashboard generates forecast, optimizes, simulates, and reopens a saved plan',async({page})=>{
  const pageErrors=[];
  page.on('pageerror',e=>pageErrors.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'Plan an EV charge'})).toBeVisible();
  await page.getByLabel('Forecast model').selectOption('hybrid');
  await page.getByRole('button',{name:'Run forecast'}).click();
  await expect(page.getByRole('img',{name:'CNN–BiLSTM–Attention and Measured energy in kWh'})).toBeVisible();
  await page.getByLabel('Hours to departure').fill('2');
  await page.getByLabel('Target SOC (%)').fill('45');
  await page.getByRole('button',{name:'Optimize charging'}).click();
  await expect(page.getByText('Target SOC is reachable')).toBeVisible();
  await page.getByRole('button',{name:'Compare charging sites'}).click();
  await expect(page.getByText('Same departure, vehicle', {exact:false})).toBeVisible();
  await page.getByRole('button',{name:'Create digital twin'}).click();
  await page.getByRole('button',{name:'Start simulation'}).click();
  await expect(page.getByText('Departure · 2/2 simulated hours')).toBeVisible({timeout:10000});
  await expect(page.getByTestId('twin-soc')).toHaveText('45.0%');
  await expect(page.getByText('Station meter receipts (2)')).toBeVisible();
  await page.getByRole('button',{name:'Simulate drive'}).click();
  await expect(page.getByText('Drive complete · 2/2 simulated hours')).toBeVisible();
  await page.getByRole('button',{name:'Model results'}).click();
  await expect(page.getByRole('heading',{name:'Forecast benchmark'})).toBeVisible();
  await page.getByRole('button',{name:'Saved plans'}).click();
  await page.getByRole('button',{name:/500e Convertible/}).click();
  await expect(page.getByText('Drive complete · 2/2 simulated hours')).toBeVisible();
  expect(pageErrors).toEqual([]);
});
